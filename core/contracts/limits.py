"""做不到的事，一次说绝（2026-11-03 P3-2）。

为什么有这个模块

2026-10-21 那天，主人让鲸鲸在群里说一句「今天下雨记得带伞」。她没有发群消息的口，
于是四个半小时里被问了 **16 次**，每次都答：

    计划早就挂在群里了，我这边按不到发出去那个键。真发还得你在群里敲一下。

这句话没有撒谎，但它留了一个假的希望——「也许换个问法就行」。所以主人试了 16 次，
最后放弃，事没办成。

**做不到不是错；说得像"还能再试一次"才是错。**

文案只放在这里一处（纯数据、无 IO、不 import 任何项目模块），由
`core/policy/channel.py::render()` 统一追加进「怎么开口」那一段，因此
所有平台、群聊与私聊都带同一套说法。要改措辞就改这个文件，别改提示词别处。
"""

from __future__ import annotations

#: 段首标签（自带宽度的原因：段落标题在设计上不进提示词，见方案文档 E-16）
REFUSAL_HEAD = "[做不到的事]"

#: 表达原则：保留能力与证据边界，不再强制固定台词或替对方决定要不要等。
REFUSAL_LINES: tuple[str, ...] = (
    "先说明当前能做和不能做的部分，不承诺做不到的结果。",
    "不说「我再试试」「我马上去办」「稍等一下应该就行」——那不是安慰，是让他白等。",
    "也不说「我按不到那个键」「计划挂在那儿了」这类像系统故障的话；证据不足时不下「永久做不了」的结论。",
    "有真实可行的替代方式就说清楚（他自己发，或者我把话写好他复制）；只有确有办法且有授权，才说可以尝试。",
    "对方追问时，核对是否有新条件或误解，回应新增的信息，不责备他重复提问。",
)

__all__ = ["REFUSAL_HEAD", "REFUSAL_LINES", "refusal_text", "NO_BLANK_HEAD", "NO_BLANK_LINES", "no_blank_text"]


def refusal_text() -> str:
    """把固定话术渲染成提示词里的一段。行数与字数由测试锁住（见 test_decisive_refusal.py）。"""
    return REFUSAL_HEAD + "\n" + "\n".join(REFUSAL_LINES)

#: 「不许交白卷」：收到表情包/图片就沉默，是 2026-11-03 洗出来的第二类高频错
#: （`feedback_samples` 里 4 次同一张表情包 + 12 次空回，见 P3-1 digest）。
NO_BLANK_HEAD = "[不许交白卷]"
NO_BLANK_LINES: tuple[str, ...] = (
    "收到表情包、图片或「拍了拍」不是没消息，是要我回一下：一句话，或一张表情（同一张不许连发）。",
    "私聊被问到必须回一句；群里没人点名可以不开口。",
)


def no_blank_text() -> str:
    """本段固定返回（不读环境、不联网），供提示词每轮注入。"""
    return NO_BLANK_HEAD + "\n" + "\n".join(NO_BLANK_LINES)
