def w(s): return sum(2 if unicodedata.east_asian_width(c) in "WF" else 1 for c in s)
def pad(s, n=IN): return s + " " * max(0, n - w(s))
def center(s):
    l = (IN - w(s)) // 2
    return " " * l + s + " " * (IN - w(s) - l)
def B(s=""):
    assert w(s) <= IN, (w(s), s)
    return "║" + pad(s) + "║"
TOP = lambda: "╔" + "═" * IN + "╗"
