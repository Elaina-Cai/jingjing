DQS = "\u2033"; C = "\u2503"
def w(s): return sum(2 if unicodedata.east_asian_width(ch) in "WF" else 1 for ch in s)
def pad(s, n): return s + " " * max(0, n - w(s))
def wrap(s, n):
    out, cur = [], ""
    for ch in s:
        if w(cur + ch) > n: out.append(cur); cur = ch
        else: cur += ch
    out.append(cur); return out
def cut(s, n):
    if w(s) <= n: return s
    out = ""
    for ch in s:
        if w(out + ch) > n - 2: break
        out += ch
    return out + "\u2026\u2026"
IN, NAMEW = 50, 10
ind = " " * (1 + 5 + 2 + NAMEW)
qpre = ind + C + " "; qcont = ind + "  "
def qlines(qwho, qtext):
    segs = str(qtext).split("\n")
    body = qwho + "\uff1a" + cut(segs[0], 60)
    lines = list(wrap(body, IN - w(qpre)))
    for seg in segs[1:3]:
        lines += list(wrap(cut(seg, 60), IN - w(qcont)))
    if len(segs) > 3:
        lines.append(cut(" ".join(segs[3:]), IN - w(qcont) - 2) + "\u2026\u2026")
    return [(qpre if i == 0 else qcont) + s for i, s in enumerate(lines)]
def body_lines(pre, body):
    out = []
    for seg in str(body).split("\n"):
        for i, s in enumerate(wrap(seg, IN - w(pre))):
            out.append((pre if (i == 0 and not out) else " " * w(pre)) + s)
    return out
def render(rows):
    out = []
    for r in rows:
        k, t, name, body = r[0], r[1], r[2], r[3]
        qwho = r[4] if len(r) > 4 else None
        qtext = r[5] if len(r) > 5 else None
        below = r[6] if len(r) > 6 else True
        if k == "sys":
            out += body_lines(" %s  %s" % (t, pad(".." + name, NAMEW)), body); continue
        pre = " %s  %s" % (t, pad(name, NAMEW))
        if qwho and not below: out += qlines(qwho, qtext)
        out += body_lines(pre, body)
        if qwho and below: out += qlines(qwho, qtext)
    return out
def box(title, rows):
    t = title if w(title) <= IN - 4 else cut(title, IN - 8)
    top = "+-- " + t + " " + "-" * max(0, IN - 4 - w(t)) + "+"
    out = [top] + ["|" + pad(l, IN) + "|" for l in render(rows)] + ["+" + "-" * IN + "+"]
    for l in out:
        assert w(l) == IN + 2, (w(l), l)
    return out
